const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { createHash } = require('node:crypto');
const { parseCharacterFile, resolveAction, safeRelative, calibrations } = require('../parser.cjs');
const { migrations, ResourcesRepository } = require('../repository.cjs');
const { ResourcesService } = require('../service.cjs');
const Database = require('better-sqlite3');
const modelDir = path.resolve(__dirname, '../../../assets/models');
const fishDir = path.resolve(__dirname, '../assets/fat-fish');
let root, db, service;
before(async () => {
  root = await fs.mkdtemp(path.join(os.tmpdir(), 'lingjing-resource-test-'));
  db = new Database(path.join(root, 'resources.sqlite'));
  db.pragma('foreign_keys = ON'); migrations.forEach(migration => db.exec(migration.sql));
  service = new ResourcesService({ db, storageRoot: path.join(root, 'managed'), legacyModelsDir: modelDir });
  await service.seed();
});
after(async () => { db?.close(); if (root && root.startsWith(os.tmpdir())) await fs.rm(root, { recursive: true, force: true }); });
test('parses the original 48-frame 2D pack and preserves explicit missing actions', async () => {
  const parsed = await parseCharacterFile(path.join(fishDir, 'character.json'));
  assert.equal(parsed.resource.kind, 'spritesheet'); assert.equal(parsed.resource.clips.length, 6);
  assert.equal(parsed.resource.clips.reduce((sum, clip) => sum + clip.frames.length, 0), 48);
  assert.equal(parsed.resource.actions.skill, null);
  assert.equal(resolveAction(parsed.resource, 'skill').clip.name, 'idle');
  assert.equal(resolveAction(parsed.resource, 'skill').fallback, true);
  assert.equal((await parseCharacterFile(path.join(fishDir, 'character.json'))).resource.contentHash, parsed.resource.contentHash);
});
test('catalog BOM, all 17 existing GLBs, attribution, and repeatable seed remain intact', async () => {
  const beforeHash = createHash('sha256').update(await fs.readFile(path.join(modelDir, 'catalog.json'))).digest('hex');
  const list = await service.list('owner-a');
  assert.equal(list.filter(resource => resource.origin === 'legacy').length, 17);
  assert.equal(list.filter(resource => resource.origin === 'legacy' && resource.availability === 'ready').length, 17);
  const shiba = list.find(resource => resource.id === 'legacy:animateddogshibainu.glb');
  assert.equal(shiba.provenance.author, 'Ari'); assert.equal(shiba.provenance.license, 'CC BY 4.0'); assert.equal(shiba.provenance.status, 'recorded');
  assert.equal(list.find(resource => resource.id === 'legacy:husky.glb').actions.idle, 'Idle');
  await service.seed(); assert.equal((await service.list('owner-a')).length, list.length);
  assert.equal(createHash('sha256').update(await fs.readFile(path.join(modelDir, 'catalog.json'))).digest('hex'), beforeHash);
});
test('imports real 2D and 3D bytes, copies assets, preserves history, and isolates owners', async () => {
  const fish = await service.importFile('owner-a', path.join(fishDir, 'character.json'));
  const shiba = await service.importFile('owner-a', path.join(modelDir, 'AnimatedDogShibaInu.glb'));
  assert.equal(fish.duplicate, false); assert.equal(shiba.resource.provenance.author, 'Ari');
  const stored = await service.assetFile('owner-a', fish.resource.id, 'fish.png');
  assert.notEqual(stored, path.join(fishDir, 'fish.png'));
  assert.deepEqual(await fs.readFile(stored), await fs.readFile(path.join(fishDir, 'fish.png')));
  const duplicate = await service.importFile('owner-a', path.join(fishDir, 'character.json'));
  assert.equal(duplicate.duplicate, true); assert.equal(duplicate.resource.id, fish.resource.id);
  assert.equal(db.prepare('SELECT count(*) AS n FROM lingjing_resource_imports WHERE resource_id = ?').get(fish.resource.id).n, 2);
  await assert.rejects(service.get('owner-b', fish.resource.id), error => error.code === 'RESOURCE_NOT_FOUND');
  await assert.rejects(service.assetFile('owner-b', fish.resource.id, 'fish.png'), error => error.code === 'RESOURCE_NOT_FOUND');
  assert.equal((await service.list('owner-b')).some(resource => resource.id === fish.resource.id), false);
});
test('one resource resolves independently for multiple pet IDs with durable owner-specific calibration', async () => {
  const id = 'builtin:fat-fish-v1', source = await service.get('owner-a', id);
  const calibration = structuredClone(source.calibration); calibration.desktop.scale = 1.23; calibration.desktop.verticalOffset = -0.12; calibration.battle.yawDeg = 30;
  const saved = await service.save('owner-a', { resourceId: id, expectedRevision: source.revision, calibration, actions: source.actions });
  assert.equal(saved.revision, 1);
  const a = await service.resolve('owner-a', { resourceId: id, petId: 'fish-a', action: 'attack', facing: 'left' });
  const b = await service.resolve('owner-a', { resourceId: id, petId: 'fish-b', action: 'idle' });
  assert.equal(a.resource.id, b.resource.id); assert.notEqual(a.petId, b.petId); assert.equal(a.calibration.mirrorX, true); assert.equal(b.calibration.mirrorX, false);
  a.calibration.scale = 2; assert.equal((await service.resolve('owner-a', { resourceId: id, petId: 'fish-b' })).calibration.scale, 1.23);
  assert.equal((await service.get('owner-b', id)).calibration.desktop.scale, 1);
  const reopened = new ResourcesService({ db, storageRoot: path.join(root, 'managed') });
  assert.equal((await reopened.get('owner-a', id)).calibration.desktop.verticalOffset, -0.12);
  await assert.rejects(service.save('owner-a', { resourceId: id, expectedRevision: 0, calibration, actions: source.actions }), error => error.code === 'REVISION_CONFLICT' && error.details.revision === 1);
});
test('legacy calibration migration is non-destructive, per-owner and never overwrites saved preferences', async () => {
  const profiles = { 'AnimatedDogShibaInu.glb': { idleOrientationYDeg: 42, poseWideScaleIdle: 1.32, battleOrientationXDeg: -20 }, 'not-found.glb': { idleOrientationYDeg: 10 } };
  const snapshot = JSON.stringify(profiles);
  assert.deepEqual(await service.migrateLegacyCalibration('legacy-owner', profiles), { migrated: 1 });
  assert.deepEqual(await service.migrateLegacyCalibration('legacy-owner', profiles), { migrated: 0 });
  assert.equal(JSON.stringify(profiles), snapshot);
  assert.equal((await service.get('legacy-owner', 'legacy:animateddogshibainu.glb')).calibration.desktop.yawDeg, 42);
  assert.equal((await service.get('owner-b', 'legacy:animateddogshibainu.glb')).calibration.desktop.yawDeg, 0);
});
test('bad JSON, truncated GLB, out-of-range frames and unsafe paths cannot change the library', async () => {
  const beforeCount = (await service.list('owner-a')).length;
  for (const unsafe of ['../outside.png', '/outside.png', 'C:/secret.png', 'images/../../outside.png', 'images\\secret.png', '%2e%2e/secret.png', 'http://remote/model.bin', 'image.png?x=1', 'bad./image.png']) assert.throws(() => safeRelative(unsafe), error => error.code === 'UNSAFE_PATH');
  const invalid = path.join(root, 'bad.json'); await fs.writeFile(invalid, '{');
  await assert.rejects(service.importFile('owner-a', invalid), error => error.code === 'INVALID_JSON');
  const glb = path.join(root, 'broken.glb'); await fs.writeFile(glb, Buffer.from('glTF-not-a-model'));
  await assert.rejects(service.importFile('owner-a', glb), error => error.code === 'INVALID_GLB');
  const manifest = JSON.parse(await fs.readFile(path.join(fishDir, 'character.json'), 'utf8'));
  await fs.copyFile(path.join(fishDir, 'fish.png'), path.join(root, 'fish.png'));
  manifest.clips.idle.frames = [100000]; await fs.writeFile(invalid, JSON.stringify(manifest));
  await assert.rejects(service.importFile('owner-a', invalid), error => error.code === 'INVALID_CLIPS');
  manifest.image = '../fish.png'; await fs.writeFile(invalid, JSON.stringify(manifest));
  await assert.rejects(service.importFile('owner-a', invalid), error => error.code === 'UNSAFE_PATH');
  assert.throws(() => calibrations({ desktop: { scale: Infinity } }), error => error.code === 'INVALID_CALIBRATION');
  assert.equal((await service.list('owner-a')).length, beforeCount);
});
test('external GLTF dependencies are copied and missing/remote/beyond-root dependencies are rejected', async () => {
  const folder = path.join(root, 'gltf'); await fs.mkdir(folder);
  const binary = Buffer.alloc(36); [0,0,0, 1,0,0, 0,1,0].forEach((value, index) => binary.writeFloatLE(value, index * 4));
  const document = { asset: { version: '2.0' }, scene: 0, scenes: [{ nodes: [0] }], nodes: [{ mesh: 0 }], meshes: [{ primitives: [{ attributes: { POSITION: 0 } }] }], buffers: [{ byteLength: 36, uri: 'triangle.bin' }], bufferViews: [{ buffer: 0, byteLength: 36 }], accessors: [{ bufferView: 0, componentType: 5126, count: 3, type: 'VEC3', min: [0,0,0], max: [1,1,0] }] };
  const file = path.join(folder, 'triangle.gltf'); await fs.writeFile(file, JSON.stringify(document)); await fs.writeFile(path.join(folder, 'triangle.bin'), binary);
  const imported = await service.importFile('owner-a', file);
  assert.equal(imported.resource.kind, 'model3d'); assert.equal(imported.resource.clips.length, 0);
  assert.equal((await fs.readFile(await service.assetFile('owner-a', imported.resource.id, 'triangle.bin'))).length, 36);
  document.buffers[0].uri = 'missing.bin'; await fs.writeFile(file, JSON.stringify(document));
  await assert.rejects(service.importFile('owner-a', file), error => error.code === 'MISSING_ASSET');
  document.buffers[0].uri = 'https://host.invalid/model.bin'; await fs.writeFile(file, JSON.stringify(document));
  await assert.rejects(service.importFile('owner-a', file), error => error.code === 'UNSAFE_PATH');
});
test('missing managed files are reported without deleting the record or import history', async () => {
  const imported = await service.importFile('missing-owner', path.join(fishDir, 'character.json'));
  await fs.unlink(await service.assetFile('missing-owner', imported.resource.id, 'fish.png'));
  assert.equal((await service.get('missing-owner', imported.resource.id)).availability, 'missing');
  assert.equal(db.prepare('SELECT count(*) AS n FROM lingjing_resource_imports WHERE resource_id=?').get(imported.resource.id).n, 1);
  assert.equal(new ResourcesRepository(db).get('missing-owner', imported.resource.id).id, imported.resource.id);
});
