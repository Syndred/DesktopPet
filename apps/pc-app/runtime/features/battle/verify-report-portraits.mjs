import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { cpSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve, sep } from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { RuntimeDataStore } = require('../../services/runtime-data-store.cjs');
const [applicationInput, profileInput, reportId] = process.argv.slice(2);
assert.ok(applicationInput && profileInput && reportId, 'Provide a built verification application, its isolated profile and a real completed report ID');
const root = resolve('artifacts/battle');
const application = resolve(applicationInput), originalProfile = resolve(profileInput);
for (const path of [application, originalProfile]) assert.ok(path.toLowerCase().startsWith((root + sep).toLowerCase()), 'Only isolated battle verification artifacts are accepted');
const output = join(root, `report-portraits-${Date.now()}`), profile = join(output, 'profile');
mkdirSync(output, { recursive: true }); cpSync(originalProfile, profile, { recursive: true });
const legacy = new RuntimeDataStore({ filePath: join(profile, 'pet-runtime-data.json'), sessionFilePath: join(profile, 'pet-auth-session.json') });
const user = legacy.getAuthSession().currentUser;
assert.ok(user?.account?.startsWith('battle-ui-'), 'The source must be the synthetic verification account');
const env = { ...process.env, PET_USER_DATA_DIR: profile }; delete env.ELECTRON_RUN_AS_NODE;
const errors = [];
const app = await electron.launch({ args: [application], env });
try {
  const page = await app.firstWindow();
  const window = await app.browserWindow(page);
  await window.evaluate(win => win.setContentSize(1280, 844, false));
  page.on('pageerror', error => errors.push(error.message));
  await page.waitForFunction(() => Boolean(window.lingjing));
  const login = await page.evaluate(account => window.lingjing.invoke('accounts', 'login', { provider: 'local', account, password: 'isolated-local-verification', rememberSession: true }), user.account);
  assert.equal(login.ok, true);
  const report = await page.evaluate(reportId => window.lingjing.invoke('battle', 'getReport', { reportId }), reportId);
  assert.equal(report.ok, true); assert.equal(report.data.status, 'finished');
  await page.evaluate(id => { location.hash = `/battle/reports/${encodeURIComponent(id)}`; }, reportId);
  await page.getByRole('region', { name: '战报详情' }).waitFor();
  await page.waitForFunction(() => document.querySelectorAll('.battle-portrait.small svg[data-framing="portrait"]').length >= 4);
  await page.waitForTimeout(350);
  const portraits = await page.locator('.battle-portrait.small svg[data-framing]').evaluateAll(elements => elements.map(element => ({ resourceId: element.getAttribute('data-resource-id'), framing: element.getAttribute('data-framing'), viewBox: element.getAttribute('viewBox') })));
  assert.ok(portraits.every(item => item.framing === 'portrait'));
  assert.ok(portraits.some(item => item.resourceId === 'builtin:lingjing-yuwan-v2'));
  assert.ok(portraits.some(item => item.resourceId === 'builtin:lingjing-shiba-v2'));
  const afterReport = await page.evaluate(reportId => window.lingjing.invoke('battle', 'getReport', { reportId }), reportId);
  assert.deepEqual(afterReport, report, 'Viewing avatars must not change the stored report or reward');
  assert.deepEqual(errors, []);
  await page.screenshot({ path: join(output, 'report-portraits.png') });
  writeFileSync(join(output, 'evidence.json'), JSON.stringify({ at: new Date().toISOString(), application, sourceProfile: originalProfile, clonedProfile: profile, reportId, preservedReport: true, rounds: report.data.rounds.length, reward: report.data.reward, portraits, errors }, null, 2));
  console.log(JSON.stringify({ output, passed: true }));
} finally { await app.close(); }
