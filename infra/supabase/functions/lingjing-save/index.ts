import { withActor, readJson, jsonResponse, LingjingAuthError, assertActorOwner } from '../_shared/lingjing-auth.ts';
import { canonical, sha256, equalHex } from '../_shared/lingjing-json.ts';
function fail(code:string,status=400):never { throw new LingjingAuthError(code,status); }
function action(value:unknown):string {
  if(typeof value!=='string'||!(/^[a-zA-Z0-9][a-zA-Z0-9:_-]{7,127}$/).test(value))fail('INVALID_REQUEST');return value as string;
}
function sqlError(error:{message?:string}) {
  const code=/LJ_([A-Z_]+)/.exec(error.message||'')?.[1]||'SYNC_UNAVAILABLE';
  const status=code==='SYNC_CONFLICT'||code==='ACTION_ID_REUSED'?409:
    /OWNER_MISMATCH|PET_OWNER|PROTECTED_STATE|MODULE_NOT_ALLOWED|CONTAINS_SECRET/.test(code)?403:
    /AUTH|SESSION|DEVICE/.test(code)?401:/INVALID|CHECKSUM/.test(code)?400:503;
  fail(code,status);
}
// Personal CAS/archive/read only. Authority is generated by domain transactions.
Deno.serve(withActor(async(request,actor)=>{
  const body=await readJson(request,26*1024*1024);
  if(body.ownerAccountId!==undefined)assertActorOwner(actor,body.ownerAccountId);
  if(body.op==='read') {
    const requested=body.actionId===undefined?null:action(body.actionId);
    const query=requested
      ?actor.client.from('lingjing_save_actions').select('action_id,revision,checksum,envelope,kind').eq('owner_id',actor.ownerAccountId).eq('action_id',requested)
      :actor.client.from('lingjing_saves').select('action_id,revision,checksum,envelope').eq('owner_id',actor.ownerAccountId);
    const {data,error}=await query.maybeSingle();if(error)sqlError(error);
    return jsonResponse({ok:true,data:data?{actionId:data.action_id,revision:data.revision,checksum:data.checksum,envelope:data.envelope,...('kind' in data?{kind:data.kind}:{})}:null});
  }
  if(body.op!=='push'&&body.op!=='archive')fail('UNSUPPORTED_OP');
  const id=action(body.actionId),envelope=body.envelope as Record<string,unknown>;
  if(!envelope||typeof envelope!=='object'||Array.isArray(envelope))fail('INVALID_SAVE');
  assertActorOwner(actor,envelope.ownerAccountId);
  const {checksum,...document}=envelope;
  if(typeof checksum!=='string'||!/^[0-9a-f]{64}$/.test(checksum)||!equalHex(await sha256(canonical(document)),checksum))fail('SAVE_CHECKSUM_MISMATCH');
  if(body.op==='push') {
    if(!Number.isSafeInteger(body.baseRevision)||(body.baseRevision as number)<0)fail('INVALID_REQUEST');
    const {data,error}=await actor.client.rpc('lingjing_push_save',{p_action_id:id,p_base_revision:body.baseRevision,p_envelope:envelope});if(error)sqlError(error);
    return jsonResponse({ok:true,data});
  }
  if(!['unverified-local','pre-conflict','before-cloud-restore'].includes(body.reason as string))fail('INVALID_REQUEST');
  const {data,error}=await actor.client.rpc('lingjing_archive_save',{p_action_id:id,p_reason:body.reason,p_envelope:envelope});if(error)sqlError(error);
  return jsonResponse({ok:true,data});
}));
