import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import ts from 'typescript';
const source='infra/supabase/functions/_shared/battle-core.js';
const output='apps/pc-app/runtime/features/battle/core.generated.cjs';
const input=readFileSync(source,'utf8').replaceAll('\r\n','\n');
const hash=createHash('sha256').update(input).digest('hex');
const compiled=ts.transpileModule(input,{fileName:'battle-core.js',compilerOptions:{allowJs:true,target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS,newLine:ts.NewLineKind.LineFeed}}).outputText;
const result=`// Generated by node scripts/battle/build-core.mjs. Do not edit.\n// Source: ${source}\n// SHA256: ${hash}\n${compiled}`;
if(process.argv.includes('--check')) {
  if(readFileSync(output,'utf8').replaceAll('\r\n','\n')!==result)throw new Error('Battle core drift: run node scripts/battle/build-core.mjs');
  console.log(`Shared battle core verified ${hash}`);
} else {writeFileSync(output,result);console.log(`Generated ${output} ${hash}`);}
